export const exerciseById = (id: string): Exercise | undefined =>
  EXERCISES.find((e) => e.id === id);

/** relevance = best score across the user's sports */
export function bestLink(ex: Exercise, userSports: string[]) {
  const mine = ex.links
    .filter((l) => userSports.includes(l.sport))
    .sort((a, b) => b.score - a.score);
  return mine[0];
}

export function rankFor(ex: Exercise, userSports: string[]): number {
  let best = 0;
  let count = 0;
  for (const l of ex.links) {
    if (!userSports.includes(l.sport)) continue;
    if (l.score > best) best = l.score;
    if (l.score >= 4) count++;
  }
  return best * 10 + count;
}
